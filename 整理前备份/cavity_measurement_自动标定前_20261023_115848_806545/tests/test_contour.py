"""Independent rounded geometry, confusing textures and failure cases."""
import sys
import json
import csv
import subprocess
import tempfile
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from cavity_measure import analyze_array, cv2, np, read_image, write_image


def rounded_mask(shape, box, radius):
    x, y, w, h = box
    mask = np.zeros(shape, np.uint8)
    cv2.rectangle(mask, (x+radius, y), (x+w-radius, y+h), 255, -1)
    cv2.rectangle(mask, (x, y+radius), (x+w, y+h-radius), 255, -1)
    for cx in (x+radius, x+w-radius):
        for cy in (y+radius, y+h-radius):
            cv2.circle(mask, (cx, cy), radius, 255, -1)
    return mask


def scene(two_complete=False, clipped=False):
    shape = (1400, 1400)
    image = np.full(shape, 145, np.uint8)
    outer = rounded_mask(shape, (100, 250, 1200, 800), 100)
    inner = cv2.erode(outer, cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (19, 19)))
    image[outer > 0] = 20
    image[inner > 0] = 200
    # A dark machining mark connected to the opening band creates an inward
    # detour in the coarse contour; convex initialization must remove it.
    cv2.ellipse(image, (700, 295), (75, 70), 0, 0, 360, 55, 5)
    cv2.line(image, (700, 250), (700, 290), 20, 3)
    rng = np.random.default_rng(15)
    for j in range(25):
        center = (int(rng.integers(180, 1200)), int(rng.integers(390, 930)))
        cv2.ellipse(image, center, (55, 35), 0, 0, 360, int(rng.integers(100, 170)), 4)
    # A partial second opening must not become the selected contour.
    other = rounded_mask(shape, (100, 1190, 1200, 800), 100)
    other_inner = cv2.erode(other, cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (19, 19)))
    image[other > 0] = 20
    image[other_inner > 0] = 190
    if two_complete:
        image = np.hstack([image, image])
    if clipped:
        image = image[300:1000, :]
    return cv2.cvtColor(cv2.GaussianBlur(image, (0, 0), 1), cv2.COLOR_GRAY2BGR), outer


class ContourTests(unittest.TestCase):
    def test_complete_rounded_boundary_ignores_texture_and_partial_neighbor(self):
        image, truth = scene()
        report, _, _ = analyze_array(image, detection="outline", boundary_side="outer")
        self.assertEqual(report["status"], "contour_detected")
        self.assertIsNone(report["dimensions"])
        contour = report["contour"]
        points = np.asarray(contour["points_px"])
        predicted = np.zeros(truth.shape, np.uint8)
        cv2.fillPoly(predicted, [np.rint(points).astype(np.int32)], 255)
        intersection = np.count_nonzero((predicted > 0) & (truth > 0))
        union = np.count_nonzero((predicted > 0) | (truth > 0))
        self.assertGreater(intersection/union, .99)
        # Independent analytic circular arc, not a square corner generated by
        # extending fitted lines. Allow the rasterized optical edge convention.
        arc = points[(points[:, 0] < 190) & (points[:, 1] < 340)]
        self.assertGreater(len(arc), 10)
        radii = np.linalg.norm(arc-[200, 350], axis=1)
        self.assertLess(np.percentile(abs(radii-100), 95), 3)
        self.assertGreater(contour["quality"]["supported_fraction"], .98)

    def test_inner_boundary_matches_independent_floor_mask_and_is_inside_outer(self):
        image, outer_truth = scene()
        inner_truth = cv2.erode(outer_truth, cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (19, 19)))
        inner_report, _, _ = analyze_array(image, detection="outline")
        outer_report, _, _ = analyze_array(image, detection="outline", boundary_side="outer")
        self.assertEqual(inner_report["contour"]["boundary_side"], "inner")
        self.assertEqual(outer_report["contour"]["boundary_side"], "outer")
        predicted = np.zeros(inner_truth.shape, np.uint8)
        cv2.fillPoly(predicted, [np.rint(inner_report["contour"]["points_px"]).astype(np.int32)], 255)
        intersection = np.count_nonzero((predicted > 0) & (inner_truth > 0))
        union = np.count_nonzero((predicted > 0) | (inner_truth > 0))
        self.assertGreater(intersection/union, .99)
        a = np.asarray(inner_report["contour"]["bbox_xywh_px"])
        b = np.asarray(outer_report["contour"]["bbox_xywh_px"])
        self.assertTrue(np.all(a[:2] > b[:2]+5))
        self.assertTrue(np.all(a[2:] < b[2:]-10))

    def test_blank_and_clipped_openings_are_rejected(self):
        for image in (np.full((600, 900, 3), 140, np.uint8), scene(clipped=True)[0]):
            with self.subTest(shape=image.shape):
                with self.assertRaises(ValueError):
                    analyze_array(image, detection="outline")

    def test_multiple_complete_openings_require_roi(self):
        image, _ = scene(two_complete=True)
        with self.assertRaisesRegex(ValueError, "Multiple"):
            analyze_array(image, detection="outline")
        report, _, _ = analyze_array(image, detection="outline", roi=[0, 150, 1400, 1000])
        self.assertEqual(report["status"], "contour_detected")

    def test_scale_maps_coordinates_without_claiming_dimensional_measurement(self):
        image, _ = scene()
        report, _, _ = analyze_array(image, detection="outline", calibration={"mm_per_pixel": .02})
        self.assertIsNone(report["dimensions"])
        self.assertEqual(report["measurement_status"], "not_performed")
        self.assertTrue(np.allclose(np.asarray(report["contour"]["points_mm"]),
                                    np.asarray(report["contour"]["points_px"])*.02))

    def test_cli_outline_saves_unicode_contour_files_and_failure_state(self):
        workspace = Path(__file__).resolve().parents[1]
        with tempfile.TemporaryDirectory(prefix=".test_", dir=workspace) as temp:
            self.assertEqual(Path(temp).resolve().parent, workspace.resolve())
            root = Path(temp)/"中文轮廓"
            image, _ = scene()
            path, out = root/"腔体.png", root/"结果"
            write_image(path, image)
            command = [sys.executable, "-X", "utf8", str(workspace/"cavity_measure.py"),
                       "measure", "--image", str(path), "--out", str(out), "--detection", "outline"]
            run = subprocess.run(command, capture_output=True, encoding="utf-8")
            self.assertEqual(run.returncode, 0, run.stderr)
            report = json.loads((out/"result.json").read_text(encoding="utf-8"))
            self.assertEqual(report["status"], "contour_detected")
            self.assertIsNone(report["dimensions"])
            self.assertEqual(read_image(out/"contour_mask.png").shape[:2], image.shape[:2])
            self.assertTrue((out/"overlay_preview.jpg").is_file())
            with (out/"contour_points.csv").open(encoding="utf-8-sig", newline="") as f:
                rows = list(csv.reader(f))
            self.assertEqual(len(rows)-1, report["contour"]["point_count"])
            write_image(path, np.full_like(image, 140))
            failed = subprocess.run(command, capture_output=True, encoding="utf-8")
            self.assertEqual(failed.returncode, 2)
            current = json.loads((out/"result.json").read_text(encoding="utf-8"))
            self.assertEqual(current["status"], "failed")
            self.assertIsNone(current["dimensions"])


if __name__ == "__main__":
    unittest.main()
